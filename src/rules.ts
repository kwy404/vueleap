export const RULES_BY_ID: ReadonlyMap<string, RuleMeta> = new Map(RULES.map((rule) => [rule.id, rule]))

export function getRule(id: string): RuleMeta {
  const rule = RULES_BY_ID.get(id)
  if (!rule) throw new Error(`Unknown rule: ${id}`)
  return rule
}
